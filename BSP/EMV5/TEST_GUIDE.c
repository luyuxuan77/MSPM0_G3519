/*===========================================================================
 * 方法5：保留循迹菜单，通过按键触发云台测试
 *===========================================================================*/

int main(void)
{
    SYSCFG_DL_init();
    uart0_init(115200U);
    app_control_init();

    // 标志：是否已经测试过云台
    static bool yuntai_tested = false;

    while (1) {
        app_control_process();

        // 如果按下K1+K2同时，触发云台测试
        if (key1_short && key2_short && !yuntai_tested) {
            key1_short = 0;
            key2_short = 0;

            printf("\r\n触发云台测试\r\n");
            yuntai_test_quick();

            yuntai_tested = true;  // 只测试一次
        }
    }
}

/*===========================================================================
 * 测试步骤建议
 *===========================================================================*/

/*
步骤1：快速测试
--------------
1. 确保步进电机已连接到UART3 (PB12-TX, PB13-RX)
2. 确保水平电机地址设置为0x01
3. 确保俯仰电机地址设置为0x02（如果有）
4. 使用 yuntai_test_quick() 测试
5. 观察串口输出和电机是否转动

步骤2：如果电机不转
------------------
- 检查UART3接线是否正确
- 检查电机地址是否正确设置
- 检查电机电源是否供电
- 增加delay时间，观察电机是否需要更长时间响应
- 使用串口助手监控UART3发送的数据

步骤3：如果电机转向错误
--------------------
- 在 yuntai_control.c 中调整dir参数（0和1互换）
- 或者在物理上调整电机连接

步骤4：如果转动角度不对
--------------------
- 检查电机细分设置（默认32细分，6400脉冲/圈）
- 调整 YT_PULSES_PER_DEG 参数
- 计算公式：脉冲数 = 角度 × (6400 / 360)

步骤5：测试成功后
--------------
- 集成到你的循迹菜单系统
- 添加激光打靶任务
- 接入视觉识别系统
*/

/*===========================================================================
 * 调试技巧
 *===========================================================================*/

/*
1. 串口输出
----------
所有测试函数都有详细的printf输出，方便调试
打开串口助手（115200波特率）观察输出

2. 减慢速度
----------
如果电机运动太快，可以降低速度参数：
Emm_V5_Pos_Control(addr, dir, 100, 20, pulses, false, false);
                              ^^^  ^^
                              速度 加速度

3. 增加等待时间
-------------
如果电机还没运动完就执行下一步，增加delay_ms时间：
delay_ms(5000);  // 等待5秒

4. 单步测试
----------
先只测试一个电机，成功后再测试另一个：
yuntai_test_single_motor(0x01, 10.0f);  // 先测水平，只转10度

5. 手动发送命令
-------------
可以直接调用底层函数测试：
uart3_init(115200);
Emm_V5_En_Control(0x01, true, false);           // 使能
delay_ms(100);
Emm_V5_Reset_CurPos_To_Zero(0x01);             // 复位
delay_ms(100);
Emm_V5_Pos_Control(0x01, 0, 200, 30, 100, false, false);  // 转动
delay_ms(2000);
Emm_V5_En_Control(0x01, false, false);          // 失能
*/

/*===========================================================================
 * 常见问题
 *===========================================================================*/

/*
问题1：编译错误 "undefined reference to yuntai_test_quick"
解决：在Keil项目中添加 BSP/YUNTAI/yuntai_test.c

问题2：电机有声音但不转
解决：可能是使能了但没有正确发送运动命令，检查串口通信

问题3：电机转动方向反了
解决：在Emm_V5_Pos_Control中把dir从0改成1，或从1改成0

问题4：转动角度不对
解决：检查电机细分设置，调整脉冲数计算公式

问题5：电机转动卡顿
解决：降低速度和加速度参数，或检查机械阻力

问题6：第二个电机（俯仰）不动
解决：检查地址是否设置为0x02，检查接线
*/
