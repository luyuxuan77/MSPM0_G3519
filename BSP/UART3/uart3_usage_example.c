#include "bsp.h"

/*******************************************************************************
 * 示例1：初始化UART3
 ******************************************************************************/
void example_uart3_init(void)
{
    uart3_init(115200);  // 初始化UART3，波特率115200
}

/*******************************************************************************
 * 示例2：使能电机控制
 ******************************************************************************/
void example_enable_motor(void)
{
    uint8_t motor_addr = 0x01;  // 电机地址

    // 使能电机
    Emm_V5_En_Control(motor_addr, true, false);
    delay_ms(10);
}

/*******************************************************************************
 * 示例3：速度控制模式
 ******************************************************************************/
void example_velocity_control(void)
{
    uint8_t motor_addr = 0x01;  // 电机地址
    uint8_t dir = 0;            // 方向：0=顺时针，1=逆时针
    uint16_t vel = 500;         // 速度：500 RPM
    uint8_t acc = 50;           // 加速度：50
    bool snF = false;           // 同步标志

    // 以500RPM顺时针运行电机
    Emm_V5_Vel_Control(motor_addr, dir, vel, acc, snF);
}

/*******************************************************************************
 * 示例4：位置控制模式
 ******************************************************************************/
void example_position_control(void)
{
    uint8_t motor_addr = 0x01;  // 电机地址
    uint8_t dir = 0;            // 方向：0=顺时针，1=逆时针
    uint16_t vel = 300;         // 速度：300 RPM
    uint8_t acc = 50;           // 加速度：50
    uint32_t clk = 6400;        // 脉冲数：6400（200步进电机转1圈）
    bool raF = false;           // 相对/绝对位置：false=相对运动
    bool snF = false;           // 同步标志

    // 电机顺时针转动1圈
    Emm_V5_Pos_Control(motor_addr, dir, vel, acc, clk, raF, snF);
}

/*******************************************************************************
 * 示例5：立即停止电机
 ******************************************************************************/
void example_stop_motor(void)
{
    uint8_t motor_addr = 0x01;

    // 立即停止电机
    Emm_V5_Stop_Now(motor_addr, false);
}

/*******************************************************************************
 * 示例6：复位当前位置为零
 ******************************************************************************/
void example_reset_position(void)
{
    uint8_t motor_addr = 0x01;

    // 将当前位置清零
    Emm_V5_Reset_CurPos_To_Zero(motor_addr);
}

/*******************************************************************************
 * 示例7：主函数中的完整使用流程
 ******************************************************************************/
void example_main_usage(void)
{
    // 步骤1：初始化UART3
    uart3_init(115200);
    delay_ms(100);

    // 步骤2：使能电机
    Emm_V5_En_Control(0x01, true, false);
    delay_ms(50);

    // 步骤3：复位当前位置
    Emm_V5_Reset_CurPos_To_Zero(0x01);
    delay_ms(50);

    // 步骤4：电机转动1圈
    Emm_V5_Pos_Control(0x01, 0, 300, 50, 6400, false, false);
    delay_ms(3000);  // 等待运动完成

    // 步骤5：反向转回
    Emm_V5_Pos_Control(0x01, 1, 300, 50, 6400, false, false);
    delay_ms(3000);

    // 步骤6：失能电机
    Emm_V5_En_Control(0x01, false, false);
}

#endif  // 示例代码结束
